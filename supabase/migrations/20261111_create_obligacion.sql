create table if not exists public.obligacion (
  id bigint generated by default as identity primary key,
  usuario_id text not null,
  titulo text not null check (length(trim(titulo)) > 0),
  fecha_vencimiento date not null,
  monto_estimado numeric(20, 2) not null default 0 check (monto_estimado >= 0),
  categoria_id text,
  estado text not null default 'Pendiente' check (estado in ('Pendiente', 'Pagado')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists obligacion_usuario_fecha_idx
  on public.obligacion (usuario_id, fecha_vencimiento);

alter table public.obligacion enable row level security;

